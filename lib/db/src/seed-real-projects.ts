async function seed() {
  const { projectsTable } = schema;
  const { sql } = await import("drizzle-orm");

  console.log("Clearing existing projects...");
  await db.execute(sql`TRUNCATE TABLE projects RESTART IDENTITY CASCADE`);

  console.log(`Inserting ${projects.length} projects...`);

  const seen = new Set<string>();
  for (const p of projects) {
    const slug = slugify(p.title);
    if (seen.has(slug)) {
      console.log(`  Skipping duplicate slug: ${slug}`);
      continue;
    }
    seen.add(slug);

    await db.insert(projectsTable).values({
      title: p.title,
      slug,
      description: p.description,
      tags: p.tags,
      techStack: p.techStack,
      status: p.status,
      featured: p.featured,
      sortOrder: p.sortOrder,
      githubUrl: p.githubUrl,
    });
    console.log(`  + ${p.title}`);
  }

  console.log(`\nDone! Inserted ${seen.size} projects.`);
  await pool.end();
}

seed().catch(console.error);
